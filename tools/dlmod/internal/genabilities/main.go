// Command genabilities writes tools/dlmod/hero_abilities.go: each hero's four abilities in slot
// order, with their class names (the keys of their text) and the base names of their icons. dlmod
// reads these from the game's scripts/heroes.vdata and scripts/abilities.vdata; this table, from
// deadlock-api's copy of the game data for one client build, is the fallback when it cannot:
//
//	go run ./internal/genabilities 6864 > hero_abilities.go
package main

import (
	"encoding/json"
	"fmt"
	"net/http"
	"os"
	"path"
	"sort"
	"strings"
	"time"
)

const api = "https://api.deadlock-api.com/v1/assets"

func get(url string, into any) error {
	client := &http.Client{Timeout: 60 * time.Second}
	req, err := http.NewRequest("GET", url, nil)
	if err != nil {
		return err
	}
	req.Header.Set("User-Agent", "deadlock-modkit")
	resp, err := client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("%s: %s", url, resp.Status)
	}
	return json.NewDecoder(resp.Body).Decode(into)
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genabilities <client build>")
		os.Exit(2)
	}
	build := os.Args[1]
	var heroes []struct {
		ClassName string            `json:"class_name"`
		Items     map[string]string `json:"items"`
	}
	var abilities []struct {
		ClassName string `json:"class_name"`
		Name      string `json:"name"`
		Image     string `json:"image"`
	}
	if err := get(api+"/heroes?only_active=true&client_version="+build, &heroes); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := get(api+"/items/by-type/ability?client_version="+build, &abilities); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	byClass := map[string]int{}
	for i, a := range abilities {
		byClass[a.ClassName] = i
	}
	sort.Slice(heroes, func(i, j int) bool { return heroes[i].ClassName < heroes[j].ClassName })
	fmt.Println("// Code generated by internal/genabilities from deadlock-api's game data for client build " + build + "; DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package main")
	fmt.Println()
	fmt.Println("// heroAbilities are each hero's abilities in slot order: class name (the key of its text in")
	fmt.Println("// citadel_heroes), English name, and the base name of its icon in panorama/images/hud/abilities.")
	fmt.Println("var heroAbilities = map[string][4][3]string{")
	for _, h := range heroes {
		var row []string
		for _, slot := range []string{"signature1", "signature2", "signature3", "signature4"} {
			i, ok := byClass[h.Items[slot]]
			if !ok {
				row = nil
				break
			}
			a := abilities[i]
			icon := strings.TrimSuffix(path.Base(a.Image), path.Ext(a.Image))
			row = append(row, fmt.Sprintf("{%q, %q, %q}", a.ClassName, a.Name, icon))
		}
		if row == nil {
			continue
		}
		fmt.Printf("\t%q: {%s},\n", strings.TrimPrefix(h.ClassName, "hero_"), strings.Join(row, ", "))
	}
	fmt.Println("}")
}
